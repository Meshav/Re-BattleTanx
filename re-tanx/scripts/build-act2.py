import json, pathlib

def mission(n, title, location, brief, debrief, rows, allies, waves, objectives, reward, **extra):
    width = len(rows[0])
    assert all(len(r) == width for r in rows), (title, [len(r) for r in rows])
    m = {"id": f"a2m{n}", "act": 2, "title": title, "location": location, "brief": brief, "debrief": debrief,
         "map": {"id": f"a2m{n}", "name": title, "cell": 10, "rows": rows},
         "allies": allies, "waves": waves, "objectives": objectives, "reward": reward}
    m.update(extra)
    return m

def W(trigger, *tanks, **kw):
    return {"trigger": trigger, "tanks": list(tanks), **kw}

def O(kind, label, **kw):
    return {"kind": kind, "label": label, **kw}

